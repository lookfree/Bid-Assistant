// 企业信息（常用文本里的一条）：标书里的响应函、授权书、报价表等**招标自带格式的表单**，
// 空位就是按它填的（单位名称、统一社会信用代码、法定代表人、住所、开户行…）。
//
// 为什么不是从营业执照图片 OCR 出来：识别认错一个字，投标函上的单位名称就是错的，
// 而这种错要到评标现场才发现。用户自己录一次，之后每一本标书都用它。

// 标题判据：**与 apps/api/src/services/credentials.ts 的 COMPANY_TITLE_RE 同形**。
// 两端各存一份（前端要判「建没建过」，后端要判「下发哪条」），改一处必须同步改另一处，
// 否则会出现前端说建好了、后端却没下发的静默不一致。
// 「信息化」「信息安全」不算：安全/IT 集成商的常用文本里常年躺着「企业信息化建设方案」
// 「企业信息安全管理制度」这种长文。被当成企业信息的后果是双向静默错误——这边不再提示用户
// 去建真的那条，后端把方案正文按「标签：值」解析出一堆垃圾字段塞进每个表单章。
export const COMPANY_TITLE_RE = /(?:企业|公司|单位|投标人)(?:基本)?信息(?!化|安全)/

/** 常用文本条目里有没有一条能当企业信息用。 */
export function hasCompanyProfile(items: { title: string }[]): boolean {
  return items.some((i) => COMPANY_TITLE_RE.test(i.title ?? ""))
}

